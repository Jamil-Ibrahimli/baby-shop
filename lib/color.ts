// Стабильный ключ цвета (независимый от локали и регистра).
// Фото товара сопоставляются с вариантами ПО ЦВЕТУ (не по size+color): одно фото
// цвета покрывает все размеры этого цвета. Ключ строим из русского названия цвета.
export function colorKey(color: string): string {
  return color.trim().toLowerCase();
}
