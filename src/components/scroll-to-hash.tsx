"use client";

import { useEffect } from "react";

/** Сколько держать подсветку найденного элемента. */
const HIGHLIGHT_MS = 2500;

/**
 * Классы подсветки. Пишутся отдельными строковыми литералами, чтобы Tailwind
 * увидел их при сборке: классы, собранные из переменных, в CSS не попадают.
 */
const HIGHLIGHT_CLASSES = ["ring-2", "ring-primary", "rounded-2xl"];

/**
 * Прокрутка к якорю из адреса (`#review-...`) ПОСЛЕ того, как содержимое
 * появилось на странице.
 *
 * Зачем нужен отдельный компонент. Уведомление ведёт на страницу с якорем на
 * конкретный отзыв, но содержимое страницы товара приезжает внутри Suspense:
 * в тот момент, когда браузер пробует доехать до якоря, на экране ещё скелетон
 * и нужного элемента в разметке нет. Прокрутка молча не срабатывает, и человек
 * оказывается наверху страницы, вынужденный искать свой отзыв глазами.
 *
 * Поэтому компонент рисуется ВНУТРИ готового содержимого — он монтируется
 * ровно тогда, когда элемент уже существует.
 *
 * Подсветка не украшение: в длинном списке похожих карточек одной прокрутки
 * мало, чтобы понять, какая из них «та самая».
 */
export function ScrollToHash() {
  useEffect(() => {
    const id = window.location.hash.slice(1);
    if (!id) return;

    // getElementById, а не querySelector: в id из cuid бывают символы,
    // ломающие селектор, а экранировать их незачем.
    const target = document.getElementById(id);
    if (!target) return;

    // Без smooth: при переходе со страницы уведомлений долгая анимация
    // выглядит как «страница сама куда-то уехала».
    target.scrollIntoView({ block: "start" });

    target.classList.add(...HIGHLIGHT_CLASSES);
    const timer = setTimeout(() => {
      target.classList.remove(...HIGHLIGHT_CLASSES);
    }, HIGHLIGHT_MS);

    return () => clearTimeout(timer);
  }, []);

  return null;
}
